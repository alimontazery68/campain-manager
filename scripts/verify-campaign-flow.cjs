const assert = require('node:assert/strict');
const path = require('node:path');
process.loadEnvFile(path.resolve(__dirname, '../apps/api/.env'));
const {PrismaClient} = require('../apps/api/node_modules/@prisma/client');
const db = new PrismaClient();
const base = process.env.TEST_BASE_URL || `http://127.0.0.1:${process.env.API_PORT || 4000}`;
let createdId;
async function main() {
  const input = {name:'تست خودکار اتصال کمپین', businessType:'مشاوره',campaignType:'جذب مشتری بالقوه',product:'جلسه مشاوره کسب‌وکار',audience:'صاحبان کسب‌وکار',duration:3,offer:{kind:'پیشنهاد خاصی ندارم',details:''},salesPath:{action:'رزرو مشاوره',details:'پیام به پشتیبانی'}};
  let response = await fetch(base+'/campaigns',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(input)});
  assert.equal(response.status,201);
  let campaign=await response.json(); createdId=campaign.id;
  assert.equal(campaign.days.length,0,'Draft must not have execution days');
  assert.equal(campaign.salesPath.action,input.salesPath.action);
  const legacy=await db.campaignDay.create({data:{campaignId:createdId,dayNumber:1,date:new Date(),phase:'اولیه',mission:'اولیه',objective:'اولیه',tasks:{create:{title:'کار اولیه',type:'SUPPORT',content:'متن محفوظ'}}},include:{tasks:true}});
  response=await fetch(base+'/campaigns/tasks/'+legacy.tasks[0].id+'/complete',{method:'PATCH'});
  assert.equal(response.status,409,'Draft completion must be rejected');
  await db.task.update({where:{id:legacy.tasks[0].id},data:{status:'DONE'}});
  const plan=require('./planning-fixtures.cjs').fixture('consulting');
  plan.phases[0].endDay=3;plan.days.push({...structuredClone(plan.days[0]),dayNumber:3});
  await db.campaign.update({where:{id:createdId},data:{aiPlan:plan}});
  response=await fetch(base+'/campaigns/'+createdId+'/approve',{method:'POST'});
  assert.equal(response.status,201);campaign=await response.json();
  assert.equal(campaign.days.length,3);
  assert.equal((await db.task.findUnique({where:{id:legacy.tasks[0].id}})).archived,true);
  assert.equal((await db.task.findUnique({where:{id:legacy.tasks[0].id}})).content,'متن محفوظ');
  assert.equal((await db.task.findUnique({where:{id:legacy.tasks[0].id}})).status,'DONE');
  assert.deepEqual(campaign.days.map(d=>d.dayNumber),[1,2,3]);
  const task=campaign.days[0].tasks[0];
  assert.equal(task.cta,'رزرو مشاوره');
  response=await fetch(base+'/campaigns/tasks/'+task.id+'/complete',{method:'PATCH'});
  assert.equal(response.status,200);
  const reread=await (await fetch(base+'/campaigns/'+createdId)).json();
  assert.equal(reread.days[0].tasks.find(t=>t.id===task.id).status,'DONE');
  assert.ok(!reread.days[0].tasks.some(t=>t.id===legacy.tasks[0].id));
  response=await fetch(base+'/campaigns/tasks/'+legacy.tasks[0].id+'/complete',{method:'PATCH'});
  assert.equal(response.status,409,'Archived task completion must be rejected');
  const list=await (await fetch(base+'/campaigns')).json();
  assert.ok(list.some(c=>c.id===createdId));
  response=await fetch(base+'/campaigns',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({...input,duration:0})});
  assert.equal(response.status,400);
  response=await fetch(base+'/campaigns/tasks/nonexistent-test-task/complete',{method:'PATCH'});
  assert.equal(response.status,404);
  console.log('PASS: create, list, reread, task completion persistence, invalid input and missing task.');
}
main().catch(error=>{console.error(error.message);process.exitCode=1;}).finally(async()=>{
  if(createdId) await db.campaign.delete({where:{id:createdId}});
  await db.$disconnect();
});
