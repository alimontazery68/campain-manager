const assert=require('node:assert/strict');
const path=require('node:path');
process.loadEnvFile(path.resolve(__dirname,'../apps/api/.env'));
const {PrismaClient}=require('../apps/api/node_modules/@prisma/client');
const {PlanningService}=require('../apps/api/dist/src/ai/planning.service');
const {validatePlan}=require('../apps/api/dist/src/ai/planning');
const {CampaignsService}=require('../apps/api/dist/src/campaigns.service');
const db=new PrismaClient();
const ids=[];
const fixture=require('./planning-fixtures.cjs').fixture('consulting');
async function main(){
  assert.throws(()=>validatePlan({...fixture,days:[fixture.days[0],fixture.days[0]]},2,1));
  assert.throws(()=>validatePlan({...fixture,days:fixture.days.map(d=>({...d,tasks:[...d.tasks,d.tasks[0]]}))},2,1));
  let calls=0;
  let captured;
  const provider={json:async(system,input)=>{calls++;captured=input;return fixture;}};
  const service=new PlanningService(db,provider);
  const campaign=await db.campaign.create({data:{name:'AI integration test',businessType:'مشاوره',campaignType:'جذب مشتری',product:'مشاوره',duration:2,days:{create:[1,2].map(dayNumber=>({dayNumber,date:new Date(),phase:'اولیه',mission:'اولیه',objective:'اولیه',tasks:{create:{title:'اولیه',type:'OPERATIONAL'}}}))}}});
  ids.push(campaign.id);
  await service.generate(campaign.id);await service.generate(campaign.id);
  assert.equal(calls,1,'Saved output must not be regenerated');
  assert.equal(captured.businessType,'مشاوره');
  assert.equal(captured.proofAssets,undefined,'Unknown proof must not become an empty list');
  const before=await db.campaign.findUnique({where:{id:campaign.id},include:{days:{include:{tasks:true}}}});
  assert.equal(before.days[0].tasks[0].title,'اولیه','Generation must not replace tasks');
  const approved=await service.approve(campaign.id);
  assert.equal(approved.status,'ACTIVE');assert.equal(approved.days[0].tasks.length,2);
  await service.approve(campaign.id);
  await db.campaign.update({where:{id:campaign.id},data:{status:'DRAFT'}});
  await db.task.update({where:{id:approved.days[0].tasks[0].id},data:{status:'DONE'}});
  await service.approve(campaign.id);
  assert.equal((await db.task.findUnique({where:{id:approved.days[0].tasks[0].id}})).status,'DONE');
  assert.equal((await db.task.findUnique({where:{id:approved.days[0].tasks[0].id}})).archived,true);
  const failService=new PlanningService(db,{json:async()=>({...fixture,days:[]})});
  const invalid=await db.campaign.create({data:{name:'Invalid test',businessType:'خدمات',campaignType:'فروش',product:'محصول',duration:2}});
  ids.push(invalid.id);
  await assert.rejects(()=>failService.generate(invalid.id));
  assert.equal((await db.campaign.findUnique({where:{id:invalid.id}})).aiPlan,null);
  const created=await new CampaignsService(db).create({name:'Optional planning context test',businessType:'آموزش',campaignType:'فروش',product:'دوره مکالمه',duration:2,offer:{kind:'بدون تخفیف',details:''},salesPath:{action:'پیام به پشتیبانی',details:'پرداخت و ارسال رسید'},objections:['وقت ندارم'],proofAssets:[{type:'video_testimonial',description:'۸ رضایت ویدیویی واقعی',count:8}],availableContentFormats:['متن'],conversionPath:{action:'پیام به پشتیبانی',steps:['توضیح','پرداخت','رسید']},previousLearnings:['توضیح زمان تمرین مهم بود']});
  ids.push(created.id);
  const contextService=new PlanningService(db,{json:async(system,input)=>{
    assert.deepEqual(input.objections,['وقت ندارم']);assert.equal(input.proofAssets[0].count,8);
    assert.deepEqual(input.conversionPath.steps,['توضیح','پرداخت','رسید']);
    assert.deepEqual(input.availableContentFormats,['متن']);
    assert.deepEqual(input.previousLearnings,['توضیح زمان تمرین مهم بود']);
    const p=require('./planning-fixtures.cjs').fixture();
    p.phases[0].proofToUse=['۸ رضایت ویدیویی واقعی'];
    p.days[0].tasks[0].requiredAsset='۸ رضایت ویدیویی واقعی';return p;
  }});
  await contextService.generate(created.id);
  const mapped=await contextService.approve(created.id);
  assert.equal(mapped.days[0].tasks[0].objective,'فهم روش');
  assert.equal(mapped.days[0].tasks[0].requiredAsset,'۸ رضایت ویدیویی واقعی');
  assert.equal(mapped.days[0].tasks[1].type,'FOLLOW_UP');
  assert.equal(mapped.aiPlan.schemaVersion,2);
  console.log('PASS: duplicate days, capacity, cached generation, preview preservation, approval persistence, invalid output rejection.');
}
main().catch(e=>{console.error(e.message);process.exitCode=1;}).finally(async()=>{for(const id of ids)await db.campaign.delete({where:{id}});await db.$disconnect();});
